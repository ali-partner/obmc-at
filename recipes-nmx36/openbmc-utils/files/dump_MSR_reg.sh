#!/bin/bash
# 1 00:1d.0 Host bridge: Intel Corporation Device 0998
# 2 00:00.4 Host bridge: Intel Corporation Device 0998
# 3 14:00.4 Host bridge: Intel Corporation Device 0998
# 4 f3:00.4 Host bridge: Intel Corporation Device 0998
# 5 fe:00.3 Host bridge: Intel Corporation Device 0998

# DUMP Address 0x00 command:
# 1 #00:1d.0 000E8000
# peci-util 0x30 0x06 0x05 0x61 0x00 reg 0x80 0x0e 0x00
# 2 #00:00.4 00004000
# peci-util 0x30 0x06 0x05 0x61 0x00 reg 0x40 0x00 0x00
# 3 #f3:00.4 0F304000
# peci-util 0x30 0x06 0x05 0x61 0x00 reg 0x40 0x30 0x0f
# 4 #fe:00.3 0Fe03000
# peci-util 0x30 0x06 0x05 0x61 0x00 reg 0x30 0xe0 0x0f
# 5 #14:00.4 01404000
# peci-util 0x30 0x06 0x05 0x61 0x00 reg 0x40 0x40 0x01

echo
echo "MER DUMP Reg:"
echo "========="
echo "********************************************************"
echo "*                     CPU0 00:00.4                   *"
echo "********************************************************"
msr=`/usr/local/bin/peci-util 0x30 0x06 0x05 0x61 0x00 0x00 0x40 0x00 0x00`
echo "DID VID: $msr"
for i in 0x00 0x04 0x08 0x10 0x14 0x18 0x20 0x24 0x28 
do
    msr=`/usr/local/bin/peci-util 0x30 0x06 0x05 0x61 0x00 $i 0x42 0x00 0x00`
    ii=$(printf "%02x" $i);
    echo "offet 0x2${ii}h: $msr"
done

echo "********************************************************"
echo "*                     CPU0 00:1d.0                   *"
echo "********************************************************"
msr=`/usr/local/bin/peci-util 0x30 0x06 0x05 0x61 0x00 0x00 0x80 0x0e 0x00`
echo "DID VID: $msr"
for i in 0x00 0x04 0x08 0x10 0x14 0x18 0x20 0x24 0x28 
do
    msr=`/usr/local/bin/peci-util 0x30 0x06 0x05 0x61 0x00 $i 0x82 0x0e 0x00`
    ii=$(printf "%02x" $i);
    echo "offet 0x2${ii}h: $msr"
done

echo "********************************************************"
echo "*                     CPU0 14:00.4                   *"
echo "********************************************************"
msr=`/usr/local/bin/peci-util 0x30 0x06 0x05 0x61 0x00 0x00 0x40 0x40 0x01`
echo "DID VID: $msr"
for i in 0x00 0x04 0x08 0x10 0x14 0x18 0x20 0x24 0x28 
do
    msr=`/usr/local/bin/peci-util 0x30 0x06 0x05 0x61 0x00 $i 0x42 0x40 0x01`
    ii=$(printf "%02x" $i);
    echo "offet 0x2${ii}h: $msr"
done

echo "********************************************************"
echo "*                     CPU0 f3:00.4                   *"
echo "********************************************************"
msr=`/usr/local/bin/peci-util 0x30 0x06 0x05 0x61 0x00 0x00 0x40 0x30 0x0f`
echo "DID VID: $msr"
for i in 0x00 0x04 0x08 0x10 0x14 0x18 0x20 0x24 0x28 
do
    msr=`/usr/local/bin/peci-util 0x30 0x06 0x05 0x61 0x00 $i 0x42 0x30 0x0f`
    ii=$(printf "%02x" $i);
    echo "offet 0x2${ii}h: $msr"
done

echo "********************************************************"
echo "*                     CPU0 fe:00.3                   *"
echo "********************************************************"
msr=`/usr/local/bin/peci-util 0x30 0x06 0x05 0x61 0x00 0x00 0x30 0xe0 0x0f`
echo "DID VID: $msr"
for i in 0x00 0x04 0x08 0x10 0x14 0x18 0x20 0x24 0x28 
do
    msr=`/usr/local/bin/peci-util 0x30 0x06 0x05 0x61 0x00 $i 0x32 0xe0 0x0f`
    ii=$(printf "%02x" $i);
    echo "offet 0x2${ii}h: $msr"
done